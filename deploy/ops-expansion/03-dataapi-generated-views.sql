/*
  appdb-data-api - Operations entities: the 2 views generated from the column contract.

  GENERATED by build_ops_views.py from ops-columns.json. Edit the JSON and regenerate; do not edit this file by hand
  (CI runs build_ops_views.py --check and fails on any difference).

  Where and when: as 01 and 02 (AppDb_dev first, then AppCatalog on the prod primary), after 01. Safe to run
  twice. Grants SELECT on each view to the DAB login's role only (role_svc_dataapi in prod, role_dev_svc_dataapi in dev). The
  base-object DENYs are 04, prod only, last.

  A contract entry can say how dev differs: "envs": ["prod"] skips the view where its source does not exist in
  AppDb_dev, and "dev-null" serves a column the dev copy lacks as NULL of the prod type. In AppCatalog
  either case stops the script instead.
*/

/* Target guard: the same as 01 and 02. Run in AppCatalog (prod primary) or AppDb_dev (dev), in the database
   itself (no USE). Anywhere else, or on a read-only copy, it raises an error and SET NOEXEC ON stops every later batch.
   In the wrong database the stop message is followed by Msg 208 compile errors; that is expected, and nothing has run. */
DECLARE @db sysname = DB_NAME(), @srv sysname = @@SERVERNAME;
IF @db NOT IN (N'AppCatalog', N'AppDb_dev')
   OR CAST(DATABASEPROPERTYEX(@db, 'Updateability') AS varchar(20)) <> 'READ_WRITE'
BEGIN
    RAISERROR(N'Stopped: run this in AppCatalog (prod primary) or AppDb_dev (dev), on a writable copy. Current: %s on %s.', 16, 1, @db, @srv);
    SET NOEXEC ON;
END;
GO
IF SCHEMA_ID(N'dataapi') IS NULL EXEC (N'CREATE SCHEMA dataapi AUTHORIZATION dbo;');
GO

/* ref.MessageTemplate -> dataapi.vw_MessageTemplate (Ops_MessageTemplate): 7 served, 9 base columns reviewed.
   Left out: content: Body; free-text: TemplateName, Description.
   BodyLength: LEN(Body).
   AppDb_dev has no Category column yet: the dev view returns it as NULL with the prod type, so the entity is the same in dev and prod. */

IF COL_LENGTH(N'ref.MessageTemplate', N'Category') IS NOT NULL
    EXEC (N'CREATE OR ALTER VIEW [dataapi].[vw_MessageTemplate]
AS
SELECT s.[TemplateId],
       s.[AccountUid],
       s.[LanguageCode],
       s.[Category],
       s.[StatusCode],
       s.[UpdatedAt],
       CAST(LEN(s.[Body]) AS int) AS [BodyLength]
FROM [ref].[MessageTemplate] AS s;');
ELSE IF DB_NAME() = N'AppDb_dev'
    EXEC (N'CREATE OR ALTER VIEW [dataapi].[vw_MessageTemplate]
AS
SELECT s.[TemplateId],
       s.[AccountUid],
       s.[LanguageCode],
       CAST(NULL AS varchar(20)) AS [Category],
       s.[StatusCode],
       s.[UpdatedAt],
       CAST(LEN(s.[Body]) AS int) AS [BodyLength]
FROM [ref].[MessageTemplate] AS s;');
ELSE
    RAISERROR(N'ref.MessageTemplate lacks a column the view serves: Category.', 16, 1);
GO

/* ref.Country -> dataapi.vw_Country (Ops_Country): 4 served, 4 base columns reviewed.
   Left out: nothing.
   A small lookup, so it may be read unfiltered. ref.Country does not exist in AppDb_dev, so the view is skipped there and the entity is prod only. */

IF OBJECT_ID(N'ref.Country') IS NOT NULL
    EXEC (N'CREATE OR ALTER VIEW [dataapi].[vw_Country]
AS
SELECT s.[CountryCode],
       s.[CountryName],
       s.[DialPrefix],
       s.[RegionCode]
FROM [ref].[Country] AS s;');
ELSE IF DB_NAME() = N'AppDb_dev'
    PRINT N'Skipped dataapi.vw_Country: ref.Country does not exist in AppDb_dev (prod-only entity Ops_Country).';
ELSE
    RAISERROR(N'ref.Country does not exist.', 16, 1);
GO

/* Grants: SELECT on each view this script created, and nothing else, to the DAB login's role. Undo one with
   REVOKE SELECT ON <view> FROM <that role>. */
DECLARE @dab sysname = CASE DB_NAME() WHEN N'AppCatalog' THEN N'role_svc_dataapi' WHEN N'AppDb_dev' THEN N'role_dev_svc_dataapi' END;
IF DATABASE_PRINCIPAL_ID(@dab) IS NULL
BEGIN
    DECLARE @db sysname = DB_NAME();
    RAISERROR(N'%s does not exist in %s: create the DAB user and role first.', 16, 1, @dab, @db);
END
ELSE
BEGIN
    DECLARE @sql nvarchar(max) = N'';
    SELECT @sql += N'GRANT SELECT ON ' + v + N' TO ' + QUOTENAME(@dab) + N'; '
    FROM (VALUES (N'dataapi.vw_MessageTemplate'),
          (N'dataapi.vw_Country')) AS t(v)
    WHERE OBJECT_ID(v) IS NOT NULL;
    EXEC sys.sp_executesql @sql;
END
GO

/* Verify (read-only): each view's columns are exactly the contract's served list, in order. Expect 0 rows. A skipped
   prod-only view in dev shows nothing here. */
WITH expected AS (SELECT v, ord, col FROM (VALUES
        (N'dataapi.vw_MessageTemplate', 1, N'TemplateId'),
        (N'dataapi.vw_MessageTemplate', 2, N'AccountUid'),
        (N'dataapi.vw_MessageTemplate', 3, N'LanguageCode'),
        (N'dataapi.vw_MessageTemplate', 4, N'Category'),
        (N'dataapi.vw_MessageTemplate', 5, N'StatusCode'),
        (N'dataapi.vw_MessageTemplate', 6, N'UpdatedAt'),
        (N'dataapi.vw_MessageTemplate', 7, N'BodyLength'),
        (N'dataapi.vw_Country', 1, N'CountryCode'),
        (N'dataapi.vw_Country', 2, N'CountryName'),
        (N'dataapi.vw_Country', 3, N'DialPrefix'),
        (N'dataapi.vw_Country', 4, N'RegionCode')) AS x(v, ord, col)),
actual AS (SELECT OBJECT_SCHEMA_NAME(c.object_id) + N'.' + OBJECT_NAME(c.object_id) AS v, c.column_id AS ord, c.name AS col
           FROM sys.columns AS c WHERE c.object_id IN (SELECT OBJECT_ID(v) FROM expected))
SELECT COALESCE(e.v, a.v) AS view_name, COALESCE(e.ord, a.ord) AS ordinal, e.col AS expected_column, a.col AS actual_column
FROM (SELECT * FROM expected WHERE OBJECT_ID(v) IS NOT NULL) AS e
FULL JOIN actual AS a ON a.v = e.v AND a.ord = e.ord
WHERE e.col IS NULL OR a.col IS NULL OR e.col <> a.col COLLATE Latin1_General_BIN2;
GO
SET NOEXEC OFF;
GO
